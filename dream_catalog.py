def expand_dreams(existing):
    """기존 자료와 중복되지 않는 정리된 주제만 콘텐츠로 추가합니다."""
    used = {entry["slug"] for entry in existing}
    result = []
    paths = sorted(DATA_DIR.glob("*.json"))
    if not paths:
        raise RuntimeError("dream_data 주제 파일을 찾지 못했습니다")

    for path in paths:
        document = json.loads(path.read_text(encoding="utf-8"))
        category, emoji = document["category"], document["emoji"]
        if category not in CONTEXTS:
            raise ValueError(f"알 수 없는 카테고리: {category}")
        focus, balance, observation, positive, cautious = CONTEXTS[category]
        for row in document["entries"]:
            slug = row["slug"].strip()
            if not slug or slug in used:
                raise ValueError(f"꿈해몽 슬러그 누락 또는 중복: {slug}")
            used.add(slug)
            subject = row["subject"].strip()
            scene_a = row["scene_a"].strip()
            scene_b = row["scene_b"].strip()
            reflection = row["reflection"].strip().rstrip("?")
            if not all((subject, scene_a, scene_b, reflection)):
                raise ValueError(f"꿈해몽 항목 내용 누락: {slug}")
            title = f"{subject} 해몽: 상황별 풀이"
            excerpt = f"{scene_a}, {scene_b}의 차이를 살펴봅니다. 꿈의 분위기와 최근 경험을 함께 비교해 보세요."
            intro = (
                f"{subject}을(를) 기억할 때는 장면 자체만큼 그때의 기분도 중요합니다. "
                f"같은 소재라도 반가웠는지, 긴장됐는지에 따라 남는 인상이 달라집니다. "
                f"특히 {focus}를 떠올려보세요. 전통적인 꿈풀이는 문화적 상징을 이야기하지만 "
                "실제 사건을 예고한다는 뜻은 아닙니다."
            )
            sections = [
                (
                    scene_a,
                    f"{scene_a} 장면을 떠올리면 먼저 꿈이 주었던 안도감이나 호기심에 주목해 보세요. "
                    f"{positive} {balance}라는 관점에서 지금 나에게 중요한 것이 무엇인지 생각해볼 수 있습니다. "
                    "꿈에서 느낀 감정과 깨어난 뒤의 감정이 같았는지도 확인해 보세요."
                ),
                (
                    scene_b,
                    f"{scene_b} 장면이 인상 깊었다면 불편함이 시작된 순간을 떠올려보세요. "
                    f"{cautious} 무엇이 가장 마음에 걸렸는지 구체적으로 적으면 "
                    "과도하게 길몽이나 흉몽으로 단정하지 않는 데 도움이 됩니다."
                ),
                (
                    "현실에서 어떤 일이 떠오르나요?",
                    f"최근 생활에서 {reflection}? 이 질문에 답하기 어렵다면, "
                    "최근 며칠 동안 반복해서 생각한 문제나 대화를 살펴보는 것부터 시작해도 좋습니다. "
                    f"{focus}와 연결되는 실제 경험이 없었다면 "
                    "잠들기 전 본 영상이나 우연히 떠오른 기억이 섞였을 수도 있습니다."
                ),
                (
                    "기억을 더 정확하게 남기는 방법",
                    f"{observation}부터 짧게 메모해보세요. "
                    f"특히 '{scene_a}'와 '{scene_b}' 중 어느 쪽에 가까웠는지를 구분하면 "
                    "막연한 해석보다 꿈속에서 느낀 감정을 돌아보는 데 유용합니다. "
                    "반복되는 불편한 꿈이 수면에 지장을 준다면 해몽보다 충분한 휴식과 수면 상태를 살피는 것이 우선입니다."
                )
            ]
            result.append({
                "slug": slug, "title": title, "category": category, "emoji": emoji,
                "excerpt": excerpt, "intro": intro, "sections": sections,
                "tip": f"꿈의 결론을 하나로 정하기보다 '{scene_a}'에서 느낀 마음과 실제 경험을 비교해 보세요.",
                "created_date": PUBLISHED_DATE
            })
    return result
